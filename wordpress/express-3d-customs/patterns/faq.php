<!-- wp:column {"className":"e3d-faq-list"} -->
<div class="wp-block-column e3d-faq-list"><!-- wp:details {"showContent":true} -->
<details class="wp-block-details" open><summary>How should I measure my door chime?</summary><!-- wp:paragraph -->
<p>Measure the chime's backplate and components, not the old cover: the widest outside width, the tallest outside height, and the depth from the wall to the furthest part. Round up to the nearest 1/16". The designer's measurement help shows examples.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How does the cover stay on?</summary><!-- wp:paragraph -->
<p>With accurate dimensions the cover slides over the backplate and stays put with friction and gravity, so no hardware is needed. If you'd rather oversize it, hang it from a pair of finishing nails for a clean, easily removable finish.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What if my bells hang below the backplate?</summary><!-- wp:paragraph -->
<p>Turn on the bell clearance cutout in step 4 of the designer. Enter the number of bells, their diameter and how far they sit from the wall, and the cover gets a matching cutout. Most exposed-chime setups can be accommodated at no extra cost.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How big can a cover be?</summary><!-- wp:paragraph -->
<p>Up to 16 inches in any direction. Any dimension of 10 inches or more adds a $10 oversize fee and $5 extra shipping, which the designer includes in the estimate.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Are the preview colors exact?</summary><!-- wp:paragraph -->
<p>Screen colors are approximate. Printed color can vary by filament brand, lighting and surface texture. Gold, Silver and Copper are premium silk filaments (+$2).</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I return a cover?</summary><!-- wp:paragraph -->
<p>Covers are made to your measurements, so covers made from incorrect dimensions can't be returned. Please double-check before ordering, or send a message if you're unsure.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How long does it take?</summary><!-- wp:paragraph -->
<p>Turnaround depends on size, materials and order volume. Express 3D Customs confirms timing after reviewing your design. Orders ship from Windsor, Colorado.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can you make something that isn't a chime cover?</summary><!-- wp:paragraph -->
<p>Yes. Custom projects are how the shop started. Send a message with what you need, photos and rough measurements.</p>
